import { build, context } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const generated = new URL(
  "../dst/bot/report/assets.generated.js",
  import.meta.url,
);
const options = {
  entryPoints: [
    fileURLToPath(new URL("./client.entry.ts", import.meta.url)),
    fileURLToPath(new URL("./styles.css", import.meta.url)),
  ],
  outdir: fileURLToPath(new URL(".", generated)),
  bundle: true,
  write: false,
  platform: "browser",
  format: "iife",
  target: "es2022",
  minify: true,
  legalComments: "none",
  plugins: [
    {
      name: "inline-report-assets",
      setup(builder) {
        builder.onEnd(async (result) => {
          if (result.errors.length) return;
          const exports = result.outputFiles.map((file) => {
            const name = file.path.endsWith(".css")
              ? "reportStyles"
              : "reportClientScript";
            return `export const ${name} = ${JSON.stringify(file.text)};`;
          });
          const source = `// Generated by npm run build:report-assets; do not edit.\n${exports.join("\n")}\n`;
          await mkdir(new URL(".", generated), { recursive: true });
          const previous = await readFile(generated, "utf8").catch((error) => {
            if (error?.code === "ENOENT") return "";
            throw error;
          });
          if (source !== previous) await writeFile(generated, source);
        });
      },
    },
  ],
};

if (process.argv.includes("--watch")) {
  const builder = await context(options);
  await builder.watch();
} else {
  await build(options);
}
